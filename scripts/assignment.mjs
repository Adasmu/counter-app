import { createHash } from 'node:crypto';

export function variantFromHash(hash) {
  if (typeof hash !== 'string' || !/^[0-9a-f]{64}$/i.test(hash)) {
    throw new Error('Očekávám 64 hexadecimálních znaků hashe SHA-256.');
  }
  return ['A', 'B', 'C', 'D'][Math.floor(Number.parseInt(hash[0], 16) / 4)];
}

export function createStudentConfig(email, name) {
  if (typeof email !== 'string' || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/u.test(email)) {
    throw new Error('Zadej univerzitní e-mail bez mezer a bez odřádkování.');
  }
  if (typeof name !== 'string' || !name.trim()) {
    throw new Error('Zadej své jméno a příjmení.');
  }
  // Exact UTF-8 input: no lowercase conversion, trim or appended newline.
  const emailSha256 = createHash('sha256').update(email, 'utf8').digest('hex');
  return { authorName: name.trim(), emailSha256, variant: variantFromHash(emailSha256) };
}

export function renderStudentConfig(config) {
  return `export type IndividualVariant = 'A' | 'B' | 'C' | 'D';
export interface StudentConfig {
  authorName: string;
  emailSha256: string;
  variant: IndividualVariant | null;
}

// Generated by npm run student. No email address is stored in the source code.
export const studentConfig: StudentConfig = ${JSON.stringify(config, null, 2)};
`;
}
